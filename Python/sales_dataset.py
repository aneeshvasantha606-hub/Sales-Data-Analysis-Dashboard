Sales_Dataset.isnull().sum()

Sales_Dataset['Quantity'] = pd.to_numeric(Sales_Dataset['Quantity'], errors='coerce')
Sales_Dataset['Quantity'] = Sales_Dataset['Quantity'].fillna(Sales_Dataset['Quantity'].median())
Sales_Dataset

Sales_Dataset['Price'] = pd.to_numeric(Sales_Dataset['Price'], errors='coerce')
Sales_Dataset['Price'] = Sales_Dataset['Price'].fillna(Sales_Dataset['Price'].median())
Sales_Dataset

Sales_Dataset['Sales'] = pd.to_numeric(Sales_Dataset['Sales'], errors='coerce')
Missing_values = Sales_Dataset['Sales'].isna()
Sales_Dataset.loc[Missing_values, 'Sales'] = Sales_Dataset['Quantity'] * Sales_Dataset['Price']
Sales_Dataset

Sales_Dataset.drop_duplicates(inplace=True)
Sales_Dataset

Sales_Dataset.to_excel('Cleaned_Sales_Dataset.xlsx', index=False)

Sales_Dataset.to_csv('Cleaned_Sales_Dataset.csv', index=False)

