Sales_Dataset.isnull().sum()

Sales_Dataset = Sales_Dataset.drop(columns=['Unnamed: 9'])
Sales_Dataset

Sales_Dataset.columns = Sales_Dataset.columns.str.strip()
Sales_Dataset

Sales_Dataset['Order_Date']=pd.to_datetime(Sales_Dataset['Order_Date'], errors='coerce')
Sales_Dataset['Order_Date'] = Sales_Dataset['Order_Date'].ffill()
Sales_Dataset

Sales_Dataset['Order_Date']

Text_columns = ['Customer_Name','Region','Product','Category']
for column in Text_columns:
  Sales_Dataset[column] = Sales_Dataset[column].str.strip()
  Sales_Dataset[column] = Sales_Dataset[column].fillna(Sales_Dataset[column].mode()[0])
Sales_Dataset

